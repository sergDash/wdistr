// Темная тема wdistr для Mozilla-приложений (Firefox, Thunderbird).
// Эти программы не читают GTK-темы и dconf — у них своя система тем:
// «системная» тема следует за pref'ом ui.systemUsesDarkTheme.
// Без него Firefox/Thunderbird открываются светлыми, даже когда вся
// система тёмная. Значение 1 = тёмная, 0 = светлая, 2 = без предпочтения.
// Файл кладётся в defaults/pref/ — дефолтный pref, перекрывается
// пользовательским about:config; pacman не трогает при обновлениях
// (управляет только файлами из манифеста пакета).
pref("ui.systemUsesDarkTheme", 1);
