#!/bin/sh
# Лечение первого входа в сессию XFCE (решено 2026-09-27, проверено вживую).
#
# Симптом: после чистой установки при первом входе курсор не виден и
# отрисовка кривая; ручное дёрганье размера окна чинило. Разбор показал:
# лечит именно НАСТОЯЩАЯ смена режима XRandR (мерцание = перестройка),
# а не сам факт изменения размера. Команда --mode ТЕКУЩЕГО режима
# бессмысленна (бездействие, проверено) — нужен переход на другой режим
# и обратно.
#
# Композитор (панель/окна) лечится отдельно: удалением пакетного автозапуска
# picom — см. custom_commands в генераторе.

LOG=/home/user/gfx-debug.log
# Маркер первого лечения: симптом бывает только при первом входе после
# чистой установки — дальше моргать нечего. После переустановки ~/.config
# новый, маркер отсутствует, лечение повторяется (ровно как паттерн болезни).
STATE="$HOME/.config/wdistr-gfx-done"

if [ -f "$STATE" ]; then
    exit 0
fi

{
    echo "== wdistr fix-gfx (первый вход): $(date -Is) =="
    xrandr
} >"$LOG" 2>&1

# Лечебная перестройка ЩАДЯЩИМ способом (идея 2026-09-27): смена частоты
# кадров при ТОМ ЖЕ разрешении. Это полноценный mode-set (лечебный механизм
# как при ручном сдвиге), но геометрия окон не меняется — визуально почти
# незаметно. Обе частоты 1280x800 (60.00 и 59.81) есть в списке режимов.
# Если не вылечит — возврат к грубому mode-swap (1366x768 -> auto).
xrandr --output Virtual-1 --mode 1280x800 --rate 59.81 >>"$LOG" 2>&1
sleep 1
xrandr --output Virtual-1 --mode 1280x800 --rate 60 >>"$LOG" 2>&1

mkdir -p "$HOME/.config"
touch "$STATE"

{
    echo "-- состояние после:"
    xrandr
    echo "== конец =="
} >>"$LOG" 2>&1
