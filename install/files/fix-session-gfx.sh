#!/bin/sh
# Лечение первого входа в сессию XFCE (решено 2026-09-27, проверено вживую).
#
# Симптом: после чистой установки при первом входе курсор не виден и
# отрисовка кривая; ручное дёрганье размера окна чинило. Разбор показал:
# лечит именно перестройка режима XRandR, а не сам факт изменения размера.
# Ранее считалось, что re-apply ТЕКОГОЖЕ режима бессмыслен (тест делался
# в условиях composite-войны и был нерентабелен) — сейчас чистая проверка.
#
# Композитор (панель/окна) лечится отдельно: удалением пакетного автозапуска
# picom — см. custom_commands в генераторе.

LOG=/home/user/gfx-debug.log
# Маркер первого лечения: симптом бывает только при первом входе после
# чистой установки. После переустановки ~/.config новый — лечение повторяется.
STATE="$HOME/.config/wdistr-gfx-done"

if [ -f "$STATE" ]; then
    exit 0
fi

# ЭКСПЕРИМЕНТ (2026-09-27, идея пользователя): прочитать ТЕКУЩИЙ режим и
# выставить его же обратно — без смены частоты и размера. Если реакция
# есть и лечение происходит — вход будет без единого видимого моргания.
# Если нет — следующая итерация вернёт rate-swap/mode-swap.
CUR="$(xrandr | sed -n 's/.*current \([0-9]*\) x \([0-9]*\).*/\1x\2/p' | head -1)"

{
    echo "== wdistr fix-gfx (первый вход): $(date -Is) =="
    echo "-- текущий режим по xrandr: ${CUR:-НЕ ПРОЧИТАН}"
    xrandr | head -3
    echo "-- re-apply текущего режима:"
    if [ -n "$CUR" ]; then
        xrandr --output Virtual-1 --mode "$CUR"
        echo "rc=$?"
    else
        echo "ПРОПУЩЕНО: режим не прочитан"
    fi
    echo "-- состояние после:"
    xrandr | head -3
} >"$LOG" 2>&1

mkdir -p "$HOME/.config"
touch "$STATE"
