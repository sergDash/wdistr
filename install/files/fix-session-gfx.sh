#!/bin/sh
# Лечение первого входа в сессию XFCE (решено 2026-09-27, проверено вживую).
#
# Симптом: после чистой установки при первом входе курсор не виден и
# отрисовка кривая; ручное дёрганье размера окна чинило. Разбор показал:
# лечит именно НАСТОЯЩАЯ смена режима XRandR (мерцание = перестройка),
# а не сам факт изменения размера. Команда --mode ТЕКУЩЕГО режима
# бессмысленна (бездействие, проверено) — нужен переход на другой режим
# и обратно.
#
# Композитор (панель/окна) лечится отдельно: удалением пакетного автозапуска
# picom — см. custom_commands в генераторе.

LOG=/home/user/gfx-debug.log

{
    echo "== wdistr fix-gfx: $(date -Is) =="
    xrandr
} >"$LOG" 2>&1

# лечебная перестройка: уход на чужой режим -> возврат к рекомендуемому
xrandr --output Virtual-1 --mode 2560x1600 >>"$LOG" 2>&1
sleep 1
xrandr --output Virtual-1 --auto >>"$LOG" 2>&1

{
    echo "-- состояние после:"
    xrandr
    echo "== конец =="
} >>"$LOG" 2>&1
