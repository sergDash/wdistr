#!/bin/sh
# Лечение первого входа в сессию XFCE — финальная механика (2026-09-27).
#
# Симптом: после чистой установки при первом входе курсор не виден,
# отрисовка кривая. Лечит перестройка режима XRandR.
#
# Итоги экспериментов (проверены вживую):
# - re-apply ТЕГОГО же режима (без смены частоты): rc=0, но НЕ лечит;
# - смена РАЗМЕРА (mode-swap): лечит, но грубо прыгает экран;
# - СМЕНА ЧАСТОТЫ при том же размере (rate-swap): лечит ОДНОЙ вспышкой,
#   геометрия окон не меняется. Скрипт сам определяет текущий размер
#   и берёт любую другую доступную частоту — работает на любом разрешении.
#
# Композитор (панель/окна) лечится отдельно: удалением пакетного автозапуска
# picom — см. custom_commands в генераторе.

LOG=/home/user/gfx-debug.log
# Маркер первого лечения: симптом бывает только при первом входе после
# чистой установки. После переустановки ~/.config новый — лечение
# повторяется (ровно как паттерн болезни).
STATE="$HOME/.config/wdistr-gfx-done"

if [ -f "$STATE" ]; then
    exit 0
fi

# текущий режим, например 1280x800
CUR="$(xrandr | sed -n 's/.*current \([0-9]*\) x \([0-9]*\).*/\1x\2/p' | head -1)"
# текущая частота (отмечена звёздочкой), например 60.00
CUR_RATE="$(xrandr | awk -v m="$CUR" '$1==m { for (i=2; i<=NF; i++) if ($i ~ /\*/) { gsub(/[*+]/, "", $i); print $i; exit } }')"
# первая доступная ЧУЖАЯ частота этого же режима, например 59.81
ALT_RATE="$(xrandr | awk -v m="$CUR" '$1==m { for (i=2; i<=NF; i++) if ($i !~ /\*/) { gsub(/[*+]/, "", $i); print $i; exit } }')"

{
    echo "== wdistr fix-gfx (первый вход): $(date -Is) =="
    echo "-- режим: ${CUR:-НЕ ПРОЧИТАН}, текущая частота: ${CUR_RATE:-?}, альтернатива: ${ALT_RATE:-НЕТ}"
    if [ -n "$CUR" ] && [ -n "$ALT_RATE" ]; then
        xrandr --output Virtual-1 --mode "$CUR" --rate "$ALT_RATE"
        echo "шаг1 (переход на $ALT_RATE): rc=$?"
        sleep 1
        xrandr --output Virtual-1 --mode "$CUR" --rate "$CUR_RATE"
        echo "шаг2 (возврат на $CUR_RATE): rc=$?"
    else
        echo "ПРОПУЩЕНО: не удалось определить режим/частоты"
    fi
    echo "-- состояние после:"
    xrandr | head -3
} >"$LOG" 2>&1

mkdir -p "$HOME/.config"
touch "$STATE"
