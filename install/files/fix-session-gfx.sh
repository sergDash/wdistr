#!/bin/sh
# Лечение первого входа в сессию XFCE — итерация 2 (2026-09-27).
# Гипотеза: сессия стартует в не перестроенном режиме дисплея; ручной сдвиг
# окна чинит всё — пытаемся сделать то же самое скриптом: смена режима
# вниз и обратно (два события перестройки), плюс курсор и перезапуск
# композитора (итерация 1 помогла панели — оставлена).
# Всё пишется в ~/gfx-debug.log для отчёта.

LOG=/home/user/gfx-debug.log

{
    echo "== wdistr fix-gfx: $(date -Is) =="
    echo "-- состояние до:"
    xrandr
} >"$LOG" 2>&1

# перезапуск оконного менеджера (итерация 1: панель стала непрозрачной)
xfwm4 --replace >/dev/null 2>&1 &
sleep 2

# смена режима: явный режим -> обратно к рекомендуемому
xrandr --output Virtual-1 --mode 1280x800 >>"$LOG" 2>&1
sleep 1
xrandr --output Virtual-1 --auto >>"$LOG" 2>&1

# курсор (уже проверен один — безвредно, пусть в логе будет попытка)
xsetroot -cursor_name left_ptr >>"$LOG" 2>&1

{
    echo "-- состояние после:"
    xrandr
    echo "== конец =="
} >>"$LOG" 2>&1
